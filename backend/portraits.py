def build_local_portrait(
    mbti_type: str,
    final_probs: Dict[str, float],
) -> str:
    poles = selected_poles(final_probs)
    ordered_axes = sorted(
        ORDER,
        key=lambda axis: normalized_axis_distance(final_probs[axis], THRESHOLDS[axis]),
        reverse=True,
    )
    strongest = [poles[axis] for axis in ordered_axes[:2]]
    softer = [poles[axis] for axis in ordered_axes[2:]]
    all_poles = strongest + softer

    # 1. Общий портрет — из двух самых выраженных полюсов
    portrait_parts = [AXIS_PROFILES[pole]["portrait"] for pole in strongest]
    portrait_text = (
        f"Тип личности — {mbti_type}. В профиле особенно заметны две черты: "
        f"во-первых, {portrait_parts[0]}. Во-вторых, {portrait_parts[1]}."
    )

    # 2. Сильные стороны — по одной с каждого из четырёх полюсов
    strengths_list: List[str] = [
        AXIS_PROFILES[pole]["strengths"][0] for pole in all_poles
    ]
    strengths_text = "Сильные стороны:\n" + "\n".join(f"— {s}" for s in strengths_list)

    # 3. Зоны роста — мягко: приоритет менее выраженным полюсам, плюс по одному пункту от сильных
    growth_list: List[str] = []
    for pole in softer:
        growth_list.append(AXIS_PROFILES[pole]["growth"][0])
    for pole in strongest:
        growth_list.append(AXIS_PROFILES[pole]["growth"][1])
    growth_text = "Возможные зоны роста:\n" + "\n".join(f"— {g}" for g in growth_list)

    # 4. Совет — от самого выраженного полюса
    tip_text = AXIS_PROFILES[strongest[0]]["tip"]

    return (
        f"1. Общий портрет.\n{portrait_text}\n\n"
        f"2. Сильные стороны.\n{strengths_text}\n\n"
        f"3. Возможные зоны роста.\n{growth_text}\n\n"
        f"4. Совет по самоподдержке и продуктивности.\n{tip_text}"
    )


def build_gigachat_portrait(
    mbti_type: str,
    percent: Dict[str, float],
    confidence: str,
    axis_levels: Dict[str, str],
) -> Optional[str]:
    if not GIGACHAT_AUTH_TOKEN or GigaChat is None:
        return None

    prompt = f"""
Ты — профессиональный психологический автор, который пишет теплые, точные и содержательные MBTI-портреты.

Локальная модель пользователя определила тип: {mbti_type}.

Стабилизированные шкалы для интерфейса:
- Экстраверсия: {percent['E']}%
- Интуиция: {percent['N']}%
- Логика: {percent['T']}%
- Рациональность: {percent['J']}%

Уверенность:
- Общая: {confidence}
- По осям: E/I={axis_levels['E']}, N/S={axis_levels['N']}, T/F={axis_levels['T']}, J/P={axis_levels['J']}

Важно:
- Сырые ответы пользователя тебе не передаются.
- Не называй проценты и не делай вид, что это точное измерение.
- Не используй диагнозы, патологии и категоричные фразы вроде «вы всегда» или «вы никогда».
- Не сравнивай человека с другими типами.
- Не добавляй дисклеймеры, оговорки о точности метода или фразы «это не диагноз»: они уже есть в интерфейсе.

Напиши 3-4 коротких абзаца на «Вы»:
1. Общий портрет.
2. Сильные стороны.
3. Возможные зоны роста.
4. Один совет по самоподдержке или продуктивности.

"""

    try:
        with GigaChat(credentials=GIGACHAT_AUTH_TOKEN, verify_ssl_certs=False) as giga:
            response = giga.chat(prompt)
        return response.choices[0].message.content.strip()
    except Exception as exc:
        print(f"Ошибка GigaChat: {exc}")
        return None


def build_portrait(
    mbti_type: str,
    final_probs: Dict[str, float],
    percent: Dict[str, float],
    confidence: str,
    axis_levels: Dict[str, str],
) -> str:
    """Пытается получить портрет от GigaChat, при неудаче — использует локальный шаблон."""
    gigachat_result = build_gigachat_portrait(
        mbti_type=mbti_type,
        percent=percent,
        confidence=confidence,
        axis_levels=axis_levels,
    )
    if gigachat_result:
        return gigachat_result
    return build_local_portrait(mbti_type=mbti_type, final_probs=final_probs)
